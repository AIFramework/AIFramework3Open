#nullable enable

namespace AI.Geometry.Constraints;

/// <summary>
/// Состояние системы ограничений в найденном решении.
/// </summary>
public enum SketchStatus
{
    /// <summary>
    /// Все ограничения выполнены, степеней свободы не осталось, лишних уравнений нет.
    /// </summary>
    WellConstrained,

    /// <summary>
    /// Ограничения выполнены, но часть неизвестных ими не определена (число степеней свободы больше нуля).
    /// </summary>
    UnderConstrained,

    /// <summary>
    /// Ограничения выполнены и определяют все неизвестные, но часть уравнений следует из остальных (избыточность).
    /// </summary>
    Redundant,

    /// <summary>
    /// Ограничения противоречат друг другу: невязка в лучшем найденном приближении не равна нулю.
    /// </summary>
    Inconsistent
}
