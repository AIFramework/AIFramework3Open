using AI.DataStructs.Algebraic;

namespace AI.Economics.Survival;

/// <summary>
/// Наблюдение анализа выживаемости: сколько клиент прожил и чем это
/// наблюдение закончилось.
/// </summary>
/// <remarks>
/// Цензурирование — главная причина, по которой отток нельзя считать
/// «процентом за месяц». Клиент, пришедший месяц назад и пока живой, не
/// является ни ушедшим, ни дожившим до года: он даёт информацию только
/// о первом месяце жизни. Выбрасывать таких клиентов — значит смещать
/// оценку в сторону быстро уходящих, а считать их выжившими — в обратную.
/// </remarks>
public sealed record SurvivalRecord
{
    /// <summary>Идентификатор клиента.</summary>
    public string Id { get; init; } = string.Empty;

    /// <summary>Длительность наблюдения до события либо до цензурирования.</summary>
    public double Time { get; init; }

    /// <summary>Наступило ли событие (отток). <c>false</c> — наблюдение цензурировано.</summary>
    public bool Event { get; init; }

    /// <summary>
    /// Причина события для анализа конкурирующих рисков: 0 — цензурирование,
    /// 1 и далее — номер причины. Для однопричинного анализа не используется.
    /// </summary>
    public int Cause { get; init; }

    /// <summary>Ковариаты клиента для регрессии Кокса.</summary>
    public Vector? Covariates { get; init; }

    /// <summary>Метка группы для сравнения кривых лог-ранговым критерием.</summary>
    public int Group { get; init; }
}
