namespace AI.Simulation.DiscreteEvent;

/// <summary>
/// Дисциплина обслуживания: кого прибор берёт следующим
/// </summary>
/// <remarks>
/// Классы заявок нумеруются с нуля, и меньший номер означает старший приоритет.
/// </remarks>
public enum QueueDiscipline
{
    /// <summary>В порядке поступления; класс заявки влияет только на статистику</summary>
    FirstComeFirstServed,

    /// <summary>
    /// Приоритет без прерывания: освободившийся прибор берёт заявку старшего класса,
    /// но начатое обслуживание не прерывается
    /// </summary>
    NonPreemptivePriority,

    /// <summary>
    /// Приоритет с прерыванием и дообслуживанием: заявка старшего класса вытесняет младшую
    /// с прибора, та возвращается в голову своей очереди и потом дообслуживается с того места,
    /// где её прервали
    /// </summary>
    PreemptiveResumePriority
}
