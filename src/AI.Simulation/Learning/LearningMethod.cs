namespace AI.Simulation.Learning;

/// <summary>Метод обучения по временным разностям</summary>
public enum LearningMethod
{
    /// <summary>
    /// Q-learning: цель обновления — лучшее действие в следующем состоянии, какое бы агент
    /// ни выбрал на самом деле. Учит оптимальную стратегию, даже исследуя случайно
    /// </summary>
    QLearning,

    /// <summary>
    /// SARSA: цель обновления — действие, которое агент действительно выберет. Учит стратегию
    /// с учётом собственного исследования, поэтому осторожнее там, где случайный шаг дорог
    /// </summary>
    Sarsa
}
