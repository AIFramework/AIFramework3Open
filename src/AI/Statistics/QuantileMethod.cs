namespace AI.Statistics;

/// <summary>
/// Правило выборочного квантиля — девять типов по Хайндману и Фану (1996).
/// </summary>
/// <remarks>
/// Числовое значение — номер типа в R (<c>quantile(x, type = …)</c>), имя — как в NumPy
/// (<c>numpy.quantile(x, q, method = …)</c>). По умолчанию везде <see cref="Linear"/> — тип 7,
/// как в R, NumPy и pandas. Типы 1–3 возвращают элементы выборки (или их полусумму), типы 4–9
/// интерполируют между соседними.
/// </remarks>
public enum QuantileMethod
{
    /// <summary>Тип 1: обратная эмпирическая функция распределения — наименьший элемент, доля не больше которого ≥ q.</summary>
    InvertedCdf = 1,

    /// <summary>Тип 2: как тип 1, но в точке разрыва берётся полусумма соседних элементов.</summary>
    AveragedInvertedCdf = 2,

    /// <summary>Тип 3: ближайший по номеру элемент; на равном расстоянии — с чётным номером.</summary>
    ClosestObservation = 3,

    /// <summary>Тип 4: линейная интерполяция эмпирической функции распределения.</summary>
    InterpolatedInvertedCdf = 4,

    /// <summary>Тип 5: кусочно-линейная функция с узлами в серединах ступеней (Хейзен).</summary>
    Hazen = 5,

    /// <summary>Тип 6: узлы в k/(n + 1) (Вейбулл).</summary>
    Weibull = 6,

    /// <summary>Тип 7: узлы в (k − 1)/(n − 1) — линейная интерполяция между порядковыми статистиками.</summary>
    Linear = 7,

    /// <summary>Тип 8: узлы в (k − 1/3)/(n + 1/3) — оценка, почти несмещённая по медиане при любом распределении.</summary>
    MedianUnbiased = 8,

    /// <summary>Тип 9: узлы в (k − 3/8)/(n + 1/4) — почти несмещённая оценка для нормальной выборки.</summary>
    NormalUnbiased = 9,
}
