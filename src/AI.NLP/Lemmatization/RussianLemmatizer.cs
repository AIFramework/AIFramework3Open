using AI.NLP.Morphology;
using System;
using System.Collections.Generic;

namespace AI.NLP.Lemmatization;

/// <summary>
/// Лемматизатор русского языка на базе правил (без внешнего словаря).
///
/// Реализует трёхуровневую схему:
/// <list type="number">
///   <item><description>словарь закрытых классов <see cref="Morphology.RussianClosedClassLexicon"/> (местоимения, служебные слова, неправильные глаголы);</description></item>
///   <item><description>извлечение возвратного -ся/-сь с рекурсивной лемматизацией основы;</description></item>
///   <item><description>таблица суффиксальных правил (прилагательные, причастия, глаголы прошедшего и настоящего времени).</description></item>
/// </list>
/// При отсутствии совпадений возвращается исходное слово в нижнем регистре
/// (без искажения стеммером). Для максимальной точности рекомендуется
/// оборачивать этот лемматизатор в <see cref="DictionaryLemmatizer"/>.
///
/// <para>
/// Правил склонения существительных здесь нет: таблица применяется ко всякому слову
/// без разбора части речи, и правило существительного портило бы глаголы не меньше,
/// чем глагольное портит существительные. Разбор с определением части речи —
/// <see cref="MorphologicalLemmatizer"/>.
/// </para>
///
/// <para>
/// Вход и выход нормализованы: нижний регистр (инвариантная культура) и ё -> е.
/// Поэтому лемматизация идемпотентна: <c>Lemmatize(Lemmatize(x)) == Lemmatize(x)</c>.
/// </para>
/// <para>
/// Разбор суффикса детерминирован: на каждый суффикс приходится ровно одно правило,
/// выигрывает самый длинный подходящий суффикс. Там, где один и тот же суффикс
/// принадлежит двум частям речи (-им, -ую), выбрана адъективная трактовка — см.
/// комментарий в таблице правил.
/// </para>
/// </summary>
[Serializable]
public sealed class RussianLemmatizer : LemmatizerBase
{
    // Гласные, шипящие и заднеязычные, а также нормализация записи взяты из
    // RussianPhonetics: теми же наборами пользуются определитель части речи
    // и правила склонения, и расходиться им нельзя.

    // Правила проиндексированы по суффиксу: разбор — это несколько обращений к хеш-таблице
    // (по одному на длину суффикса), а не линейный проход с EndsWith по всей таблице.
    // Побочный, но важный эффект: раньше правила сортировались нестабильной List.Sort,
    // и при совпадении длины суффиксов победитель зависел от реализации сортировки.
    private static readonly Dictionary<string, Rule> RulesBySuffix;
    private static readonly int MaxSuffixLength;
    private static readonly int MinSuffixLength;

    static RussianLemmatizer()
    {
        var index = new Dictionary<string, Rule>(StringComparer.Ordinal);
        int max = 0;
        int min = int.MaxValue;

        foreach (Rule r in BuildRules())
        {
            // Последнее правило выигрывает: адъективные идут в таблице ниже глагольных,
            // поэтому неоднозначные суффиксы (-им, -ую) разрешаются как прилагательные.
            index[r.Suffix] = r;
            if (r.Suffix.Length > max) max = r.Suffix.Length;
            if (r.Suffix.Length < min) min = r.Suffix.Length;
        }

        RulesBySuffix = index;
        MaxSuffixLength = max;
        MinSuffixLength = min == int.MaxValue ? 1 : min;
    }

    /// <summary>
    /// Общий потокобезопасный экземпляр (лемматизатор stateless и immutable).
    /// </summary>
    public static readonly RussianLemmatizer Instance = new RussianLemmatizer();

    /// <inheritdoc />
    public override string Lemmatize(string word)
    {
        if (string.IsNullOrEmpty(word))
            return word ?? string.Empty;

        // Нормализация: в нижний регистр, ё -> е, убираем крайние пробелы.
        // Именно ToLowerInvariant: ToLower() зависит от текущей культуры (турецкая «I»)
        // и делал бы результат непредсказуемым на не-русской локали.
        string w = RussianPhonetics.Normalize(word.Trim());
        if (w.Length == 0) return string.Empty;

        return LemmatizeNormalized(w);
    }


    private static string LemmatizeNormalized(string w)
    {
        // 1. Словарь закрытых классов (местоимения, служебные слова, неправильные глаголы).
        if (RussianClosedClassLexicon.TryGetLemmaNormalized(w, out string lemma))
            return lemma;

        // 2. Возвратный постфикс -ся/-сь: лемматизируем основу, затем приклеиваем «ся».
        //    Этот шаг перехватывает ВСЕ возвратные формы, поэтому в таблице правил
        //    возвратных суффиксов нет — они были бы недостижимы.
        if (w.Length > 3 && (w.EndsWith("ся", StringComparison.Ordinal) || w.EndsWith("сь", StringComparison.Ordinal)))
        {
            string baseForm = w.Substring(0, w.Length - 2);
            if (RussianClosedClassLexicon.TryGetLemmaNormalized(baseForm, out string baseLemma))
                return baseLemma + "ся";

            // Если правила не сработали, ApplyRules вернёт основу без изменений —
            // результат тот же, отдельная ветка не нужна.
            return ApplyRules(baseForm) + "ся";
        }

        // 3. Обычный суффиксальный разбор.
        return ApplyRules(w);
    }

    private static string ApplyRules(string w)
    {
        // Longest match wins: пробуем суффиксы от самого длинного к самому короткому.
        int start = Math.Min(MaxSuffixLength, w.Length);

        for (int len = start; len >= MinSuffixLength; len--)
        {
            string suffix = w.Substring(w.Length - len);
            if (!RulesBySuffix.TryGetValue(suffix, out Rule r))
                continue;

            int stemLength = w.Length - len;
            if (stemLength < r.MinStem)
                continue;

            string stem = w.Substring(0, stemLength);

            if (r.NeedsVowelInStem && !RussianPhonetics.ContainsVowel(stem))
                continue;

            // Правила для прилагательных: автоопределение мягкого варианта.
            string replacement = r.Replacement;
            if (r.Kind == RuleKind.Adjective && stem.Length > 0)
            {
                char last = stem[stem.Length - 1];
                if (RussianPhonetics.IsHushOrVelar(last))
                    replacement = "ий";
                else if (r.SoftFlexion)
                    replacement = "ий";
                else
                    replacement = "ый";
            }

            return stem + replacement;
        }

        return w;
    }


    // ==================== ПРАВИЛА ====================

    private enum RuleKind
    {
        Generic,
        Adjective,
    }

    private sealed class Rule
    {
        public string Suffix;
        public string Replacement;
        public int MinStem;
        public bool NeedsVowelInStem;
        public RuleKind Kind;
        /// <summary>Исходная флексия из «мягкой» серии (яя, ее, ие, юю, ...).</summary>
        public bool SoftFlexion;
    }

    private static Rule G(string suf, string repl, int minStem = 2, bool needsVowel = true) =>
        new Rule { Suffix = suf, Replacement = repl, MinStem = minStem, NeedsVowelInStem = needsVowel, Kind = RuleKind.Generic };

    private static Rule A(string suf, bool soft, int minStem = 2) =>
        new Rule { Suffix = suf, Replacement = soft ? "ий" : "ый", MinStem = minStem, NeedsVowelInStem = true, Kind = RuleKind.Adjective, SoftFlexion = soft };

    // ВАЖНО: возвратных суффиксов (-ся/-сь) в таблице нет намеренно — их снимает шаг 2
    // в LemmatizeNormalized, и такие правила были бы мёртвыми. Например «учился»
    // превращается в «учил» -> правило «ил» -> «учить» -> «учиться».
    // Порядок значим: адъективные правила идут последними и выигрывают неоднозначные суффиксы.
    private static List<Rule> BuildRules()
    {
        return new List<Rule>
        {
            // ---- ПРИЧАСТИЯ действительные прошедшего времени: -вш... -> -ть ----
            G("вшими",   "ть",   3), G("вшего",  "ть", 3), G("вшему",  "ть", 3),
            G("вшим",    "ть",   3), G("вших",   "ть", 3), G("вшей",   "ть", 3),
            G("вшую",    "ть",   3), G("вшею",   "ть", 3),
            G("вшая",    "ть",   3), G("вшее",   "ть", 3), G("вшие",   "ть", 3),
            G("вший",    "ть",   3), G("вшем",   "ть", 3),
            // Деепричастия -в/-вши намеренно пропущены: одиночное «в» в конце слова
            // чаще встречается у существительных (нрав, рукав) и даёт ложные срабатывания.

            // ---- ПРИЧАСТИЯ действительные настоящего: -ющ/-ущ/-ящ/-ащ ----
            // Мягкая серия -> -ить
            G("ящими",   "ить",  3), G("ящего",  "ить", 3), G("ящему",  "ить", 3),
            G("ящим",    "ить",  3), G("ящих",   "ить", 3), G("ящую",   "ить", 3),
            G("ящей",    "ить",  3), G("ящая",   "ить", 3), G("ящее",   "ить", 3),
            G("ящие",    "ить",  3), G("ящий",   "ить", 3), G("ящем",   "ить", 3),
            G("ящ",      "ить",  3),

            // Жёсткая серия после шипящих -> -ать
            G("ащими",   "ать",  3), G("ащего",  "ать", 3), G("ащему",  "ать", 3),
            G("ащим",    "ать",  3), G("ащих",   "ать", 3), G("ащую",   "ать", 3),
            G("ащей",    "ать",  3), G("ащая",   "ать", 3), G("ащее",   "ать", 3),
            G("ащие",    "ать",  3), G("ащий",   "ать", 3), G("ащем",   "ать", 3),
            G("ащ",      "ать",  3),

            // -ующ- -> -овать (рисующий -> рисовать)
            G("ующими",  "овать", 3), G("ующего", "овать", 3), G("ующему", "овать", 3),
            G("ующим",   "овать", 3), G("ующих",  "овать", 3), G("ующую",  "овать", 3),
            G("ующей",   "овать", 3), G("ующая",  "овать", 3), G("ующее",  "овать", 3),
            G("ующие",   "овать", 3), G("ующий",  "овать", 3), G("ующем",  "овать", 3),

            // -ющ- (прочие) -> -ть
            G("ющими",   "ть",   3), G("ющего",  "ть", 3), G("ющему",  "ть", 3),
            G("ющим",    "ть",   3), G("ющих",   "ть", 3), G("ющую",   "ть", 3),
            G("ющей",    "ть",   3), G("ющая",   "ть", 3), G("ющее",   "ть", 3),
            G("ющие",    "ть",   3), G("ющий",   "ть", 3), G("ющем",   "ть", 3),

            // -ущ- -> -ать (несут -> нести: не всегда корректно, но для -ущ/-ющ основной путь к -ть)
            G("ущими",   "ать",  3), G("ущего",  "ать", 3), G("ущему",  "ать", 3),
            G("ущим",    "ать",  3), G("ущих",   "ать", 3), G("ущая",   "ать", 3),
            G("ущее",    "ать",  3), G("ущие",   "ать", 3), G("ущий",   "ать", 3),
            G("ущем",    "ать",  3),

            // Страдательные причастия -нный/-тый намеренно пропущены:
            // слишком часто совпадают с прилагательными (длинный, красный, богатый,
            // открытый) — без POS-теггера разрешить неоднозначность нельзя.
            // Для таких случаев используйте DictionaryLemmatizer.

            // ---- ГЛАГОЛ: прошедшее время -л/-ла/-ло/-ли с сохранением вокала ----
            G("али",  "ать", 2), G("ала",  "ать", 2), G("ало",  "ать", 2), G("ал",  "ать", 2),
            G("яли",  "ять", 2), G("яла",  "ять", 2), G("яло",  "ять", 2), G("ял",  "ять", 2),
            G("или",  "ить", 2), G("ила",  "ить", 2), G("ило",  "ить", 2), G("ил",  "ить", 2),
            G("ели",  "еть", 2), G("ела",  "еть", 2), G("ело",  "еть", 2), G("ел",  "еть", 2),
            G("ыли",  "ыть", 2), G("ыла",  "ыть", 2), G("ыло",  "ыть", 2), G("ыл",  "ыть", 2),
            G("оли",  "оть", 2), G("ола",  "оть", 2), G("оло",  "оть", 2), G("ол",  "оть", 2),
            G("ули",  "уть", 2), G("ула",  "уть", 2), G("уло",  "уть", 2), G("ул",  "уть", 2),

            // ---- ГЛАГОЛ: настоящее/будущее время -> инфинитив ----
            // Высокочастотные суффиксы с однозначной трактовкой.
            G("ываете","ывать", 2), G("ываешь","ывать", 2), G("ываем","ывать", 2),
            G("ывают", "ывать", 2), G("ывает", "ывать", 2), G("ываю","ывать", 2),
            G("иваете","ивать", 2), G("иваешь","ивать", 2), G("иваем","ивать", 2),
            G("ивают", "ивать", 2), G("ивает", "ивать", 2), G("иваю","ивать", 2),
            G("ует",   "овать", 2), G("уют",   "овать", 2), G("уешь","овать", 2),
            G("уете",  "овать", 2), G("уем",   "овать", 2),
            G("еваете","евать", 2), G("еваешь","евать", 2), G("евают","евать", 2),
            G("евает", "евать", 2), G("еваю",  "евать", 2), G("еваем","евать", 2),

            // 2-е спряжение: -ишь/-ит/-им/-ите/-ят/-ат -> -ить
            G("ишь",   "ить",   2), G("ите",   "ить",   2),
            G("ит",    "ить",   2), G("ят",    "ить",   2), G("ат",    "ить",   2),

            // 1-е спряжение: -ешь/-ет/-ем/-ете/-ут/-ют -> -ать (по умолчанию)
            G("аешь",  "ать",   2), G("ает",   "ать",   2), G("аем",   "ать",   2),
            G("аете",  "ать",   2), G("ают",   "ать",   2), G("аю",    "ать",   2),
            G("еешь",  "еть",   2), G("еет",   "еть",   2), G("еем",   "еть",   2),
            G("еете",  "еть",   2), G("еют",   "еть",   2), G("ею",    "еть",   2),
            G("яешь",  "ять",   2), G("яет",   "ять",   2), G("яем",   "ять",   2),
            G("яете",  "ять",   2), G("яют",   "ять",   2), G("яю",    "ять",   2),
            G("ешь",   "ать",   2), G("ет",    "ать",   2), G("ем",    "ать",   2),
            G("ете",   "ать",   2), G("ют",    "ать",   2), G("ут",    "ать",   2),

            // ---- ПРИЛАГАТЕЛЬНЫЕ ----
            // Идут последними: суффиксы -им и -ую принадлежат сразу двум частям речи
            // (говорим/синим, рисую/новую), и разрешаются в пользу прилагательного.
            // Причина — размер парадигмы: адъективная трактовка «схлопывает» к одной лемме
            // весь набор из дюжины падежных форм, тогда как глагольная спасает ровно одну
            // форму, а остальные и так покрыты правилами прошедшего времени.
            A("ейшими", false), A("ейшему", false), A("ейшего", false),
            A("ейшим",  false), A("ейших",  false), A("ейшей",  false),
            A("ейшая",  false), A("ейшее",  false), A("ейшие",  false),
            A("ейший",  false), A("ейшем",  false),

            A("ыми", false), A("ими", true),
            A("ого", false), A("его", true),
            A("ому", false), A("ему", true),
            A("ых",  false), A("их",  true),
            A("ая",  false), A("яя",  true),
            A("ое",  false), A("ее",  true),
            A("ые",  false), A("ие",  true),
            A("ую",  false), A("юю",  true),
            A("ым",  false), A("им",  true),
            A("ый",  false), A("ий",  true),
        };
    }
}
