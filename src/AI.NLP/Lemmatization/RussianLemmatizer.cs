    private static Dictionary<string, string> BuildExceptions()
    {
        var d = new Dictionary<string, string>(StringComparer.Ordinal);

        // Ключи и значения проходят ту же нормализацию, что и вход Lemmatize.
        // Без этого формы с «ё» («моё», «чьё», «своё») были недостижимы: поиск шёл
        // по уже приведённому «мое», а в таблице лежало «моё».
        void Add(string lemma, params string[] forms)
        {
            string canonical = Normalize(lemma);
            d[canonical] = canonical;
            foreach (string f in forms)
                d[Normalize(f)] = canonical;
        }

        // Личные местоимения
        Add("я", "меня", "мне", "мной", "мною");
        Add("ты", "тебя", "тебе", "тобой", "тобою");
        Add("он", "его", "него", "ему", "нему", "им", "ним", "нём", "нем");
        Add("она", "её", "ее", "неё", "нее", "ей", "ней", "ею", "нею");
        Add("оно");
        Add("мы", "нас", "нам", "нами");
        Add("вы", "вас", "вам", "вами");
        Add("они", "их", "них", "ими", "ними");
