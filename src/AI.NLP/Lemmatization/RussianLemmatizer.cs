using System;
using System.Collections.Generic;

namespace AI.NLP.Lemmatization;

/// <summary>
/// Лемматизатор русского языка на базе правил (без внешнего словаря).
///
/// Реализует трёхуровневую схему:
/// <list type="number">
///   <item><description>справочник исключений для высокочастотных местоимений, вспомогательных и неправильных глаголов;</description></item>
///   <item><description>извлечение возвратного -ся/-сь с рекурсивной лемматизацией основы;</description></item>
///   <item><description>таблица суффиксальных правил (прилагательные, причастия, глаголы прошедшего и настоящего времени).</description></item>
/// </list>
/// При отсутствии совпадений возвращается исходное слово в нижнем регистре
/// (без искажения стеммером). Для максимальной точности рекомендуется
/// оборачивать этот лемматизатор в <see cref="DictionaryLemmatizer"/>.
///
/// <para>
/// Вход и выход нормализованы: нижний регистр (инвариантная культура) и ё -> е.
/// Поэтому лемматизация идемпотентна: <c>Lemmatize(Lemmatize(x)) == Lemmatize(x)</c>.
/// </para>
/// <para>
/// Разбор суффикса детерминирован: на каждый суффикс приходится ровно одно правило,
/// выигрывает самый длинный подходящий суффикс. Там, где один и тот же суффикс
/// принадлежит двум частям речи (-им, -ую), выбрана адъективная трактовка — см.
/// комментарий в таблице правил.
/// </para>
/// </summary>
[Serializable]
public sealed class RussianLemmatizer : LemmatizerBase
{
    private static readonly char[] VowelsArray = { 'а', 'е', 'и', 'о', 'у', 'ы', 'э', 'ю', 'я' };
    private static readonly HashSet<char> Vowels = new HashSet<char>(VowelsArray);
    // Шипящие и заднеязычные — после них в прилагательных «мягкий» вариант: -ий
    private static readonly HashSet<char> HushAndVelar = new HashSet<char>(new[] { 'г', 'к', 'х', 'ж', 'ш', 'щ', 'ч' });

    private static readonly Dictionary<string, string> Exceptions = BuildExceptions();

    // Правила проиндексированы по суффиксу: разбор — это несколько обращений к хеш-таблице
    // (по одному на длину суффикса), а не линейный проход с EndsWith по всей таблице.
    // Побочный, но важный эффект: раньше правила сортировались нестабильной List.Sort,
    // и при совпадении длины суффиксов победитель зависел от реализации сортировки.
    private static readonly Dictionary<string, Rule> RulesBySuffix;
    private static readonly int MaxSuffixLength;
    private static readonly int MinSuffixLength;

    static RussianLemmatizer()
    {
        var index = new Dictionary<string, Rule>(StringComparer.Ordinal);
        int max = 0;
        int min = int.MaxValue;

        foreach (Rule r in BuildRules())
        {
            // Последнее правило выигрывает: адъективные идут в таблице ниже глагольных,
            // поэтому неоднозначные суффиксы (-им, -ую) разрешаются как прилагательные.
            index[r.Suffix] = r;
            if (r.Suffix.Length > max) max = r.Suffix.Length;
            if (r.Suffix.Length < min) min = r.Suffix.Length;
        }

        RulesBySuffix = index;
        MaxSuffixLength = max;
        MinSuffixLength = min == int.MaxValue ? 1 : min;
    }

    /// <summary>
    /// Общий потокобезопасный экземпляр (лемматизатор stateless и immutable).
    /// </summary>
    public static readonly RussianLemmatizer Instance = new RussianLemmatizer();

    /// <inheritdoc />
    public override string Lemmatize(string word)
    {
        if (string.IsNullOrEmpty(word))
            return word ?? string.Empty;

        // Нормализация: в нижний регистр, ё -> е, убираем крайние пробелы.
        // Именно ToLowerInvariant: ToLower() зависит от текущей культуры (турецкая «I»)
        // и делал бы результат непредсказуемым на не-русской локали.
        string w = Normalize(word.Trim());
        if (w.Length == 0) return string.Empty;

        return LemmatizeNormalized(w);
    }

    /// <summary>Приведение к канонической записи: нижний регистр (инвариантно) и ё -> е.</summary>
    private static string Normalize(string s) => s.ToLowerInvariant().Replace('ё', 'е');

    private static string LemmatizeNormalized(string w)
    {
        // 1. Справочник исключений (высокочастотные/неправильные формы).
        if (Exceptions.TryGetValue(w, out string lemma))
            return lemma;

        // 2. Возвратный постфикс -ся/-сь: лемматизируем основу, затем приклеиваем «ся».
        //    Этот шаг перехватывает ВСЕ возвратные формы, поэтому в таблице правил
        //    возвратных суффиксов нет — они были бы недостижимы.
        if (w.Length > 3 && (w.EndsWith("ся", StringComparison.Ordinal) || w.EndsWith("сь", StringComparison.Ordinal)))
        {
            string baseForm = w.Substring(0, w.Length - 2);
            if (Exceptions.TryGetValue(baseForm, out string baseLemma))
                return baseLemma + "ся";

            // Если правила не сработали, ApplyRules вернёт основу без изменений —
            // результат тот же, отдельная ветка не нужна.
            return ApplyRules(baseForm) + "ся";
        }

        // 3. Обычный суффиксальный разбор.
        return ApplyRules(w);
    }

    private static string ApplyRules(string w)
    {
        // Longest match wins: пробуем суффиксы от самого длинного к самому короткому.
        int start = Math.Min(MaxSuffixLength, w.Length);

        for (int len = start; len >= MinSuffixLength; len--)
        {
            string suffix = w.Substring(w.Length - len);
            if (!RulesBySuffix.TryGetValue(suffix, out Rule r))
                continue;

            int stemLength = w.Length - len;
            if (stemLength < r.MinStem)
                continue;

            string stem = w.Substring(0, stemLength);

            if (r.NeedsVowelInStem && !ContainsVowel(stem))
                continue;

            // Правила для прилагательных: автоопределение мягкого варианта.
            string replacement = r.Replacement;
            if (r.Kind == RuleKind.Adjective && stem.Length > 0)
            {
                char last = stem[stem.Length - 1];
                if (HushAndVelar.Contains(last))
                    replacement = "ий";
                else if (r.SoftFlexion)
                    replacement = "ий";
                else
                    replacement = "ый";
            }

            return stem + replacement;
        }

        return w;
    }

    private static bool ContainsVowel(string s)
    {
        for (int i = 0; i < s.Length; i++)
            if (Vowels.Contains(s[i])) return true;
        return false;
    }

    // ==================== ПРАВИЛА ====================

    private enum RuleKind
    {
        Generic,
        Adjective,
    }

    private sealed class Rule
    {
        public string Suffix;
        public string Replacement;
        public int MinStem;
        public bool NeedsVowelInStem;
        public RuleKind Kind;
        /// <summary>Исходная флексия из «мягкой» серии (яя, ее, ие, юю, ...).</summary>
        public bool SoftFlexion;
    }

    private static Rule G(string suf, string repl, int minStem = 2, bool needsVowel = true) =>
        new Rule { Suffix = suf, Replacement = repl, MinStem = minStem, NeedsVowelInStem = needsVowel, Kind = RuleKind.Generic };

    private static Rule A(string suf, bool soft, int minStem = 2) =>
        new Rule { Suffix = suf, Replacement = soft ? "ий" : "ый", MinStem = minStem, NeedsVowelInStem = true, Kind = RuleKind.Adjective, SoftFlexion = soft };

