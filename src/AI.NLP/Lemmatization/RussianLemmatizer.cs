    private static readonly char[] VowelsArray = { 'а', 'е', 'и', 'о', 'у', 'ы', 'э', 'ю', 'я' };
    private static readonly HashSet<char> Vowels = new HashSet<char>(VowelsArray);
    // Шипящие и заднеязычные — после них в прилагательных «мягкий» вариант: -ий
    private static readonly HashSet<char> HushAndVelar = new HashSet<char>(new[] { 'г', 'к', 'х', 'ж', 'ш', 'щ', 'ч' });

    private static readonly Dictionary<string, string> Exceptions = BuildExceptions();
    private static readonly Rule[] Rules = BuildRules();

    /// <summary>
    /// Общий потокобезопасный экземпляр (лемматизатор stateless и immutable).
    /// </summary>
    public static readonly RussianLemmatizer Instance = new RussianLemmatizer();

    /// <inheritdoc />
    public override string Lemmatize(string word)
    {
        if (string.IsNullOrEmpty(word))
            return word ?? string.Empty;

        // Нормализация: в нижний регистр, ё -> е, убираем крайние пробелы.
        string w = word.Trim().ToLower().Replace('ё', 'е');
        if (w.Length == 0) return string.Empty;

        return LemmatizeNormalized(w);
    }

    private static string LemmatizeNormalized(string w)
    {
        // 1. Справочник исключений (высокочастотные/неправильные формы).
        if (Exceptions.TryGetValue(w, out string lemma))
            return lemma;

        // 2. Возвратный постфикс -ся/-сь: лемматизируем основу, затем приклеиваем «ся».
        if (w.Length > 3 && (w.EndsWith("ся", StringComparison.Ordinal) || w.EndsWith("сь", StringComparison.Ordinal)))
        {
            string baseForm = w.Substring(0, w.Length - 2);
            if (Exceptions.TryGetValue(baseForm, out string baseLemma))
                return baseLemma + "ся";

            string reflexiveLemma = ApplyRules(baseForm);
            if (!ReferenceEquals(reflexiveLemma, baseForm))
                return reflexiveLemma + "ся";
            // Правила не сработали — оставляем как есть (но всё равно добавляем ся).
            return baseForm + "ся";
        }

        // 3. Обычный суффиксальный разбор.
        return ApplyRules(w);
    }

    private static string ApplyRules(string w)
    {
        for (int i = 0; i < Rules.Length; i++)
        {
            Rule r = Rules[i];
            if (w.Length - r.Suffix.Length < r.MinStem) continue;
            if (!w.EndsWith(r.Suffix, StringComparison.Ordinal)) continue;

            string stem = w.Substring(0, w.Length - r.Suffix.Length);

            if (r.NeedsVowelInStem && !ContainsVowel(stem))
                continue;

            // Правила для прилагательных: автоопределение мягкого варианта.
            string replacement = r.Replacement;
            if (r.Kind == RuleKind.Adjective && stem.Length > 0)
            {
                char last = stem[stem.Length - 1];
                if (HushAndVelar.Contains(last))
                    replacement = "ий";
                else if (r.SoftFlexion)
                    replacement = "ий";
                else
                    replacement = "ый";
            }

            return stem + replacement;
        }

        return w;
    }

    private static bool ContainsVowel(string s)
    {
        for (int i = 0; i < s.Length; i++)
            if (Vowels.Contains(s[i])) return true;
        return false;
    }

