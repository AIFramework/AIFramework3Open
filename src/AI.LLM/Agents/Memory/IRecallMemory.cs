namespace AI.LLM.Agents.Memory;

/// <summary>
/// Память, умеющая отдать относящееся к запросу отдельным текстом, а не готовым контекстом.
/// </summary>
/// <remarks>
/// <see cref="IAgentMemory.BuildContextAsync"/> возвращает контекст целиком — со своим системным
/// промптом и своим сообщением пользователя. Два таких контекста не склеить: получится два
/// системных промпта и два запроса. Поэтому тому, кто собирает контекст из нескольких источников
/// (<see cref="CompositeMemory"/>), нужно именно «что вспомнилось» — текстом, который можно
/// вклеить в чужой промпт.
/// <para>
/// Отдельный интерфейс, а не расширение <see cref="IAgentMemory"/>: вспоминать по запросу умеет
/// не всякая память. Скользящее окно и сжатие хранят ход разговора, а не отвечают на вопрос
/// «что из прошлого относится к делу», и навязывать им такой метод значило бы заставить их
/// возвращать заглушку.
/// </para>
/// </remarks>
public interface IRecallMemory
{
    /// <summary>Заголовок секции воспоминаний в системном промпте.</summary>
    /// <remarks>
    /// Один на всех, кто вспоминает и кто вклеивает: иначе одна и та же секция называется
    /// по-разному в зависимости от того, использовали память отдельно или в составе композита.
    /// </remarks>
    public const string SectionHeader = "### Релевантные воспоминания из прошлых диалогов:";

    /// <summary>
    /// Возвращает относящиеся к запросу воспоминания.
    /// </summary>
    /// <param name="query">Текущий запрос пользователя.</param>
    /// <returns>Текст воспоминаний; <c>null</c> либо пусто — вспомнить нечего.</returns>
    Task<string> RecallAsync(string query);
}
