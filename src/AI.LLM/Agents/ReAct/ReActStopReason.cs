namespace AI.LLM.Agents.ReAct;

/// <summary>
/// Причина остановки цикла. Позволяет отличить полноценный ответ от исчерпания бюджета или
/// сбоя, не разбирая текст ответа.
/// </summary>
/// <remarks>
/// Важно: ни одна из причин, кроме <see cref="TerminalTool"/> и <see cref="Cancelled"/>,
/// не отменяет синтез ответа. Собранные наблюдения — это результат работы, и выбрасывать их
/// из-за исчерпания лимита нельзя.
/// </remarks>
public enum ReActStopReason
{
    /// <summary>Модель сочла собранных данных достаточными и завершила цикл сама.</summary>
    FinalAnswer = 0,

    /// <summary>Инструмент завершил ход собственным результатом.</summary>
    TerminalTool = 1,

    /// <summary>Исчерпан лимит итераций.</summary>
    IterationLimit = 2,

    /// <summary>Исчерпан лимит времени на прогон.</summary>
    TimeLimit = 3,

    /// <summary>Цикл перестал продвигаться: повторы одного действия или череда падений.</summary>
    NoProgress = 4,

    /// <summary>Ни один источник не дал инструментов — работать нечем.</summary>
    NoTools = 5,

    /// <summary>Модель не отвечает или её ответ не удаётся разобрать.</summary>
    PolicyFailure = 6,

    /// <summary>Прогон отменён вызывающей стороной.</summary>
    Cancelled = 7,

    /// <summary>
    /// Необработанный сбой внутри цикла. Причина — в <see cref="ReActResult.Error"/>.
    /// <para>
    /// Такой сбой попадает в результат, а не улетает исключением: поток событий уже начат,
    /// и вызывающей стороне удобнее разобрать одно терминальное событие, чем оборачивать
    /// перечисление в try/catch — вокруг <c>yield return</c> это к тому же запрещено языком.
    /// </para>
    /// </summary>
    EngineFailure = 8,
}
