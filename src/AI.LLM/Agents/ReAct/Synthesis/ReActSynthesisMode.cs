namespace AI.LLM.Agents.ReAct.Synthesis;

/// <summary>Когда запускать синтез итогового ответа.</summary>
public enum ReActSynthesisMode
{
    /// <summary>Никогда: ответом становится текст, присланный моделью при завершении.</summary>
    Never = 0,

    /// <summary>Только если своего текста у цикла нет — например, кончились шаги или время.</summary>
    WhenNoAnswer = 1,

    /// <summary>
    /// Всегда. Нужно там, где решение шага генерируется в урезанном бюджете и в JSON-режиме:
    /// такой канал не годится для итогового текста, и присланное моделью используется
    /// только как черновик.
    /// </summary>
    Always = 2,
}
