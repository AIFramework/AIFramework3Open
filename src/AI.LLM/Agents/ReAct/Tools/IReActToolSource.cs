namespace AI.LLM.Agents.ReAct.Tools;

/// <summary>
/// Источник инструментов на один прогон. Каждый источник сам решает, доступен ли он в данном
/// контексте: настроен ли провайдер, подключена ли интеграция, есть ли у пользователя права.
/// <para>
/// Благодаря этому цикл не знает имён инструментов и не нуждается в списке-переключателе:
/// добавление инструмента — это добавление источника, а не правка условия внутри цикла.
/// </para>
/// </summary>
public interface IReActToolSource
{
    /// <summary>Возвращает инструменты, доступные в данном контексте.</summary>
    /// <param name="context">Контекст прогона.</param>
    /// <returns>Инструменты; пустая последовательность, если источник неприменим.</returns>
    /// <remarks>
    /// Метод синхронный намеренно: он вызывается один раз на прогон при сборке набора, и
    /// ввод-вывод в нём означал бы поход в сеть или базу на каждом ходе. Данные, которые нужно
    /// получить асинхронно, следует подготовить заранее и замкнуть в источнике.
    /// </remarks>
    IEnumerable<IReActTool> GetTools(ReActRunContext context);
}
