namespace AI.LLM.Agents.ReAct.Rendering;

/// <summary>
/// Превращает след прогона в текст для модели и отвечает за его объём.
/// <para>
/// Это единственное место во всём цикле, где след укорачивается. Вынесено отдельно
/// намеренно: когда обрезкой занимается сам цикл «по длине строки», рано или поздно
/// отрезается начало — а начало содержит самые свежие наблюдения только если строку
/// собирали с конца. На практике выходило наоборот, и модель переставала видеть, что уже
/// сделала. У отдельного компонента контракт один и проверяется отдельным тестом.
/// </para>
/// </summary>
public interface IReActTraceRenderer
{
    /// <summary>Рендерит след в текст наблюдений.</summary>
    /// <param name="trace">След прогона.</param>
    /// <returns>Текст для модели; пустая строка, если след пуст.</returns>
    string Render(ReActTrace trace);
}
