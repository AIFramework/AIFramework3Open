namespace AI.Physics.Acoustics;

/// <summary>Геометрия источника шума: от неё зависит, как быстро уровень спадает с расстоянием</summary>
public enum SourceGeometry
{
    /// <summary>Точечный: машина, выстрел, голос — минус 6 дБ на удвоение расстояния</summary>
    Point,

    /// <summary>
    /// Линейный некогерентный: дорога с плотным потоком — минус 3 дБ на удвоение расстояния;
    /// мощность источника задаётся на метр длины
    /// </summary>
    Line,
}
