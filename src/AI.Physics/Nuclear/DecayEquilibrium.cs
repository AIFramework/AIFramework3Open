namespace AI.Physics.Nuclear;

/// <summary>Вид равновесия между родительским и дочерним нуклидами</summary>
public enum DecayEquilibrium
{
    /// <summary>
    /// Равновесия нет: дочерний нуклид стабилен или живёт дольше родительского и накапливается
    /// </summary>
    None,

    /// <summary>
    /// Подвижное: родительский живёт дольше, но не на порядки. Дочерний спадает вместе
    /// с родительским, и отношение их активностей постоянно и больше доли ветвления
    /// </summary>
    Transient,

    /// <summary>
    /// Вековое: родительский живёт в тысячи раз дольше. Активности сравниваются, и по дочернему
    /// можно измерять родительский
    /// </summary>
    Secular
}
