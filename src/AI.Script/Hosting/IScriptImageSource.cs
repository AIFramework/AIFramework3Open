namespace AI.Script.Hosting;

/// <summary>
/// Значение, которое умеет нарисовать себя картинкой.
/// </summary>
/// <remarks>
/// Отчёту нужен график КАРТИНКОЙ: Word не исполняет описание Plotly. Нарисовать его может только
/// модуль, который этот график построил, а вставить в документ — модуль документов. Контракт
/// лежит в ядре, чтобы один не ссылался на другой: документы не знают про графики, графики —
/// про документы.
/// </remarks>
public interface IScriptImageSource
{
    /// <summary>Подпись картинки; может быть пустой.</summary>
    string ImageTitle { get; }

    /// <summary>Рисует картинку в PNG заданного размера в пикселях.</summary>
    byte[] RenderPng(int width, int height);
}
