namespace AI.Script.Binding;

/// <summary>
/// Модуль, у которого часть функций зависит от служб хоста.
/// </summary>
/// <remarks>
/// Генератор картинок, распознавание текста, декодер видео дает хост, и без них функция
/// существует в языке, но работать не может. Молча прятать ее нельзя: модель, не найдя функцию,
/// выдумает замену. Поэтому функция остается в справке с пометкой «не подключено», проверка
/// предупреждает о ней до запуска, а вызов отказывает внятно.
/// </remarks>
public interface IScriptAvailability
{
    /// <summary>Почему функция не работает у этого хоста; <c>null</c> — работает.</summary>
    /// <param name="function">Имя функции внутри модуля, без пространства.</param>
    string? Unavailable(string function);
}
