var processor = new Processor();
int totalTests = 0;
int passedTests = 0;
var failedTests = new List<string>();

void Test(string name, string script, string expected, bool exactMatch = false)
{
    totalTests++;
    Console.WriteLine($"[{totalTests}] {name}");
    Console.Write($"    Скрипт: {script.Replace("\n", "\\n")}");
    
    try
    {
        var actual = ProcessorOutputReader.GetLastExpressionDisplay(processor, script).Trim();
        
        bool passed = exactMatch 
            ? actual == expected 
            : actual.Contains(expected) || actual.StartsWith(expected.Split(' ')[0]);
        
        if (passed)
        {
            Console.WriteLine($" [{actual}]");
            passedTests++;
        }
        else
        {
            Console.WriteLine($"");
            Console.WriteLine($"       Ожидалось: {expected}");
            Console.WriteLine($"       Получено:  {actual}");
            failedTests.Add($"{totalTests}. {name}");
        }
    }
    catch (Exception ex)
    {
        Console.WriteLine($" ОШИБКА");
        Console.WriteLine($"       {ex.Message}");
        failedTests.Add($"{totalTests}. {name} (Exception)");
    }
}

