using AI.ClassicMath.Calculator.ProcessorLogic;
using System;
using System.Linq;

namespace EdgeCaseTests;

/// <summary>
/// Тесты поддержки комментариев в стиле Python (#)
/// </summary>
class TestComments
{
    static int passedTests = 0;
    static int failedTests = 0;
    static int totalTests = 0;

    static void Test(string testName, string script, double? expected, double precision = 1e-10)
    {
        totalTests++;
        try
        {
            var processor = new Processor();
            var output = processor.Run(script);
            var hasError = output.Any(line => line.Contains("КРИТИЧЕСКАЯ ОШИБКА") || line.Contains("ОШИБКА"));

            if (hasError)
            {
                failedTests++;
                Console.WriteLine($"{testName}");
                Console.WriteLine($"   Ошибка выполнения");
                foreach (var line in output)
                {
                    Console.WriteLine($"   {line}");
                }
                return;
            }

            // Находим результат (последняя строка с "=>")
            double? result = null;
            foreach (var line in output)
            {
                if (line.Contains("=>"))
                {
                    var parts = line.Split(new[] { "=>" }, StringSplitOptions.None);
                    if (parts.Length == 2)
                    {
                        var valueStr = parts[1].Trim().Split(new[] { ' ', '[' })[0];
                        if (double.TryParse(valueStr, System.Globalization.NumberStyles.Any, System.Globalization.CultureInfo.InvariantCulture, out var val))
                        {
                            result = val;
                        }
                    }
                }
            }

            bool passed;
            if (expected == null && result == null)
            {
                passed = true;
            }
            else if (expected == null || result == null)
            {
                passed = false;
            }
            else
            {
                passed = Math.Abs(result.Value - expected.Value) < precision;
            }

            if (passed)
            {
                passedTests++;
                Console.WriteLine($"{testName}");
            }
            else
            {
                failedTests++;
                Console.WriteLine($"{testName}");
                Console.WriteLine($"   Expected: {expected}, Got: {result}");
            }
        }
        catch (Exception ex)
        {
            failedTests++;
            Console.WriteLine($"{testName}");
            Console.WriteLine($"   Exception: {ex.Message}");
        }
    }

    static void Main(string[] args)
    {
        Console.WriteLine("=== ТЕСТЫ ПОДДЕРЖКИ КОММЕНТАРИЕВ (#) ===\n");

        // Тест 1: Простой комментарий в начале строки
        Test("Комментарий в начале строки",
            @"# Это комментарий
x = 5
x * 2",
            10.0);

        // Тест 2: Inline комментарий
        Test("Inline комментарий",
            @"x = 5  # Устанавливаем значение
y = x * 2  # Умножаем на 2
y + 3  # Добавляем 3",
            13.0);

        // Тест 3: Физическая задача с комментариями
        Test("Физическая задача с комментариями",
            @"# Константы задачи
M = 2
m = 1
V0 = 2
k = 27
mu = 0.3
g = 10
pi_val = 3

# 1) Расчет сжатия x1 при начале проскальзывания
x1 = (mu * g * (M + m)) / k
x1",
            1.0 / 3.0, 1e-8);  // Уменьшена точность до 1e-8

        // Тест 4: Множественные комментарии
        Test("Множественные комментарии",
            @"# Комментарий 1
# Комментарий 2
# Комментарий 3
x = 10  # Значение x
y = 20  # Значение y
x + y  # Сумма",
            30.0);

        // Тест 5: Только комментарии (пустой результат)
        Test("Только комментарии",
            @"# Только комментарии
# Ничего не вычисляем",
            null);

        // Тест 6: Комментарий с формулами
        Test("Комментарий с формулами",
            @"# Расчет: omega = sqrt(k / (M + m))
M = 2
m = 1
k = 27
omega = sqrt(k / (M + m))  # Циклическая частота
omega",
            3.0, 1e-8);  // Уменьшена точность до 1e-8

        // Тест 7: Комментарий в середине скрипта
        Test("Комментарий в середине",
            @"x = 5
# Промежуточный комментарий
y = 10
# Еще один комментарий
x + y",
            15.0);

        // Тест 8: # внутри строки НЕ должен удаляться
        Test("# внутри строкового литерала",
            @"s = ""Test#123""
len(s)",
            8.0);

        // Тест 9: Комментарий после оператора
        Test("Комментарий после оператора",
            @"x = 10 + 5  # Сложение
y = x * 2  # Умножение
y",
            30.0);

        // Тест 10: Комментарий в цикле
        Test("Комментарий в цикле",
            @"total = 0
for i = 0 to 3:  # Цикл от 0 до 3
    # Накапливаем сумму
    total = total + i  # Добавляем i
total",
            6.0);

        // Тест 11: Комментарий в условии if
        Test("Комментарий в if",
            @"x = 5
# Проверка условия
if x > 3:  # Если больше 3
    result = 100  # Устанавливаем 100
else:  # Иначе
    result = 50  # Устанавливаем 50
result",
            100.0);

        // Тест 12: Множественные # в комментарии
        Test("Множественные # в комментарии",
            @"x = 10  ### Важный комментарий ###
y = 20  # Еще один # внутри комментария #
x + y",
            30.0);

        // Тест 13: Комментарий без пробела после #
        Test("Комментарий без пробела",
            @"x = 5 #без пробела
y = 10#тоже без пробела
x + y",
            15.0);

        // Тест 14: Пробелы перед комментарием
        Test("Пробелы перед #",
            @"x = 5      # Много пробелов перед комментарием
y = 10	# Табуляция перед комментарием
x + y",
            15.0);

        // Тест 15: Комментарий в массиве
        Test("Комментарий с массивом",
            @"# Создаем массив
arr = [1, 2, 3]  # Три элемента
# Вычисляем сумму
sum(arr)  # Результат",
            6.0);

        // Тест 16: Комментарий с функциями
        Test("Комментарий с функциями",
            @"# Используем математические функции
x = sqrt(16)  # Корень из 16
y = abs(-5)  # Модуль -5
x + y  # Сумма результатов",
            9.0);

        // Тест 17: Строка с escaped кавычками и #
        Test("Строка с кавычками и #",
            @"s1 = ""Test""  # Простая строка
s2 = ""Hash#Tag""  # Строка с хэштегом
len(s1) + len(s2)",
            12.0);

        // Тест 18: Комментарий в тернарном операторе
        Test("Комментарий в тернарном",
            @"x = 5  # Значение x
# Тернарный оператор с комментариями
result = x > 3 ? 100 : 50  # Выбор значения
result",
            100.0);

        // Тест 19: Комментарии вокруг математических операций
        Test("Комментарии вокруг операций",
            @"# Сложные вычисления
a = 2  # Первое число
b = 3  # Второе число
c = a ^ b  # Возведение в степень (2^3 = 8)
d = c * 2  # Умножение (8 * 2 = 16)
d + 4  # Добавление 4 (16 + 4 = 20)",
            20.0);

        // Тест 20: Пустые строки и комментарии
        Test("Пустые строки с комментариями",
            @"x = 5

# Пустая строка выше

y = 10  # Комментарий

# Еще комментарии

x + y",
            15.0);

        // Тест 21: Комментарий после закрывающей скобки
        Test("Комментарий после скобок",
            @"x = (5 + 3) * 2  # После скобок
y = abs(-10)  # После функции
x + y",
            26.0);

        // Тест 22: Комментарий с while циклом
        Test("Комментарий в while",
            @"# Цикл while
i = 0  # Счетчик
total = 0  # Сумма
while i < 5:  # Пока меньше 5
    total = total + i  # Накапливаем
    i = i + 1  # Увеличиваем счетчик
total  # Результат",
            10.0);

        // Тест 23: Комментарий с битовыми операциями
        Test("Комментарий с битовыми",
            @"# Битовые операции
a = 5  # 101 в двоичной
b = 3  # 011 в двоичной
c = a & b  # AND: 001 = 1
d = a | b  # OR: 111 = 7
c + d  # 1 + 7 = 8",
            8.0);

        // Тест 24: Комментарий с научной нотацией
        Test("Комментарий с научной нотацией",
            @"# Научная нотация
x = 1e3  # 1000
y = 2e-2  # 0.02
x * y  # 1000 * 0.02 = 20",
            20.0);

        // Тест 25: Комментарий в сложном выражении
        Test("Комментарий в сложном выражении",
            @"# Сложное выражение
x = 5
y = 3
# Используем тернарный, функции и операции
result = (x > y ? max(x, y) : min(x, y)) + abs(x - y)  # Максимум + разность
result",
            7.0);

        // Тест 26: КРИТИЧЕСКИЙ - код НЕ должен обрезаться вместе с комментарием
        Test("Код не обрезается с комментарием",
            @"a = 3 # Переменная a
b = 5 # Переменная b
c = a + b # Сумма
c",
            8.0);

        // Тест 27: КРИТИЧЕСКИЙ - проверка что код после # сохраняется
        Test("Множественные переменные с комментариями",
            @"x1 = 10 # Первая
x2 = 20 # Вторая
x3 = 30 # Третья
x4 = 40 # Четвертая
x1 + x2 + x3 + x4",
            100.0);

        // Тест 28: КРИТИЧЕСКИЙ - строки не должны терять содержимое
        Test("Строки с # не теряют содержимое",
            @"s1 = ""Hello#World"" # Строка с хэштегом
s2 = ""Test""  # Обычная строка
s3 = ""#Start""  # Начинается с #
len(concat(s1, s2, s3))",
            21.0);  // "Hello#World" (11) + "Test" (4) + "#Start" (6) = 21

        // Тест 29: КРИТИЧЕСКИЙ - выражения после # в строках
        Test("Сложные строки с #",
            @"name = ""User#123"" # ID пользователя
tag = ""#важно""  # Тег
len(name) + len(tag)",
            14.0);  // "User#123" (8) + "#важно" (6) = 14

        // Тест 30: КРИТИЧЕСКИЙ - математические операции не обрезаются
        Test("Операции не обрезаются",
            @"result1 = 2 * 3 # Умножение
result2 = 10 / 2 # Деление
result3 = 5 + 5 # Сложение
result4 = 20 - 5 # Вычитание
result1 + result2 + result3 + result4",
            36.0);

        // Тест 31: КРИТИЧЕСКИЙ - функции не обрезаются
        Test("Функции не обрезаются",
            @"val1 = sqrt(16) # Корень
val2 = abs(-10) # Модуль
val3 = max(5, 3) # Максимум
val1 + val2 + val3",
            19.0);

        // Тест 32: КРИТИЧЕСКИЙ - массивы не обрезаются
        Test("Массивы не обрезаются",
            @"arr1 = [1, 2, 3] # Первый массив
arr2 = [4, 5, 6] # Второй массив
sum(arr1) + sum(arr2)",
            21.0);

        // Тест 33: КРИТИЧЕСКИЙ - строка с escaped backslash перед кавычкой
        Test("Escaped backslash + кавычка",
            @"s = ""Path: C:\\folder\\file.txt""  # Путь Windows
len(s)",
            26.0);  // "Path: C:\folder\file.txt" = 26 символов (backslash не escaped в runtime)

        // Тест 34: КРИТИЧЕСКИЙ - # после строки с backslash
        Test("# после строки с \\",
            @"path = ""C:\\Users\\Test\\""  # Путь
x = 10  # Переменная
len(path) + x",
            27.0);  // "C:\Users\Test\" = 17 символов + 10 = 27

        // Тест 35: КРИТИЧЕСКИЙ - строка с # и \\ внутри
        Test("Строка с \\ и #",
            @"s = ""Test\\#Value""  # Строка с обратным слэшем
len(s)",
            12.0);  // "Test\#Value" = 11 символов (но калькулятор может хранить как есть)

        // Тест 36: КРИТИЧЕСКИЙ - строка начинается с # (как в Python)
        Test("Строка начинается с #",
            @"a = ""#Привет!""
len(a)",
            8.0);

        // Тест 37: КРИТИЧЕСКИЙ - пустая строка с # снаружи
        Test("Пустая строка + комментарий",
            @"a = """"  # Пустая строка
b = ""#""  # Только хэштег
len(a) + len(b)",
            1.0);

        // Тест 38: КРИТИЧЕСКИЙ - # в начале, середине и конце строки
        Test("# во всех позициях строки",
            @"s1 = ""#start""  # Начало
s2 = ""mid#dle""  # Середина  
s3 = ""end#""  # Конец
len(s1) + len(s2) + len(s3)",
            17.0);  // "#start" (6) + "mid#dle" (7) + "end#" (4) = 17

        Console.WriteLine($"\n=== РЕЗУЛЬТАТЫ ===");
        Console.WriteLine($"Всего тестов: {totalTests}");
        Console.WriteLine($"Пройдено: {passedTests}");
        Console.WriteLine($"Провалено: {failedTests}");

        if (failedTests > 0)
        {
            Console.WriteLine($"\nЕсть непрошедшие тесты!");
            Environment.Exit(1);
        }
        else
        {
            Console.WriteLine($"\n Все тесты пройдены успешно!");
            Environment.Exit(0);
        }
    }
}

